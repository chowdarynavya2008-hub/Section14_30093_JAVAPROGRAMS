public class Arraycount

{

    public static void main(String [] args)

    {

        int arr[] = {10, 20, 34, 4, 5};

        int count = 0;

        for (int i = 0; i < arr.length; i++)

        {

            count++;

        }

        System.out.print("Number of elements in array is : " + count);
   
       }

}